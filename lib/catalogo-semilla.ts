export function slugify(texto: string) {
  return texto
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Catálogo semilla. `ahora` permite fechar los productos de forma relativa. */
export function catalogoSemilla(ahora: Date = new Date("2026-10-01T12:00:00-05:00")): Producto[] {
  return S.map((s, i) => {
    const { diasDesdeCreado, tallas, ...resto } = s;
    return {
      ...resto,
      id: `p${String(i + 1).padStart(2, "0")}`,
      slug: slugify(s.nombre),
      tallas: tallas.map(([talla, existencias]) => ({ talla, existencias })),
      imagenes: [],
      creado: new Date(ahora.getTime() - diasDesdeCreado * 86400000).toISOString(),
    };
  });
}

